#!/usr/bin/env node
// Pre-generates the daily puzzle archive into www/data/archive.js.
//   node scripts/build-archive.js [start] [end]             build the whole range in one go
//   node scripts/build-archive.js part <file> <start> <end>  build one slice (run several in parallel)
//   node scripts/build-archive.js merge <start> <file>...    join slices into www/data/archive.js
const fs = require('fs');
const path = require('path');
const { generateFor } = require('../www/js/rater.js');

const ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const VERSION = 2; // bump when the generator changes, so apps know saved boards no longer match
const SEED = 'spotlock2:';

function encode(p) {
  // re-index cells in row-major order
  const order = p.cells.map((_, i) => i).sort((a, b) =>
    p.cells[a][0] - p.cells[b][0] || p.cells[a][1] - p.cells[b][1]);
  const newIdx = new Array(order.length);
  order.forEach((old, n) => { newIdx[old] = n; });
  const cellRegion = new Array(p.cells.length);
  p.regions.forEach((rg, ri) => rg.cells.forEach(c => { cellRegion[c] = ri; }));
  const grid = new Array(p.rows * p.cols).fill('.');
  p.cells.forEach(([r, c], i) => { grid[r * p.cols + c] = ALPHA[cellRegion[i]]; });
  const rules = p.regions.map(rg => {
    const r = rg.rule;
    if (!r) return '';
    return r.type === 'sum' ? String(r.value) : r.type === 'lt' ? '<' + r.value
      : r.type === 'gt' ? '>' + r.value : r.type === 'eq' ? '=' : '!';
  }).join(',');
  const doms = p.dominoes.map(d => d.join('')).join('');
  const sol = p.solution.map((s, i) => {
    const d = p.dominoes[i];
    const forward = s.va === d[0] && s.vb === d[1];
    const a = forward ? s.a : s.b, b = forward ? s.b : s.a;
    return newIdx[a] + '-' + newIdx[b];
  }).join(',');
  return [p.rows + ',' + p.cols, grid.join(''), rules, doms, sol].join('|');
}

function buildDays(start, end, onDay) {
  const days = [];
  const d1 = new Date(end + 'T00:00:00Z');
  for (let d = new Date(start + 'T00:00:00Z'); d <= d1; d.setUTCDate(d.getUTCDate() + 1)) {
    const iso = d.toISOString().slice(0, 10);
    days.push(['easy', 'medium', 'hard'].map(level => {
      const p = generateFor(SEED + iso, level);
      if (p.regions.length > ALPHA.length) throw new Error('too many regions on ' + iso);
      return encode(p);
    }));
    if (onDay) onDay(iso, days);
  }
  return days;
}
function write(start, days) {
  const out = '/* Generated by scripts/build-archive.js — do not edit by hand. */\n' +
    'self.SPOTLOCK_ARCHIVE = ' + JSON.stringify({ version: VERSION, start, days }) + ';\n';
  fs.writeFileSync(path.join(__dirname, '../www/data/archive.js'), out);
  console.log('wrote', days.length, 'days,', (out.length / 1024).toFixed(0), 'KB');
}

module.exports = { encode, SEED, VERSION };
if (require.main !== module) return;

const args = process.argv.slice(2);
if (args[0] === 'part') {
  const [, file, start, end] = args;
  const days = buildDays(start, end, (iso, sofar) => { if (sofar.length % 20 === 0) console.log(iso); });
  fs.writeFileSync(file, JSON.stringify(days));
  console.log('done', days.length);
} else if (args[0] === 'merge') {
  const [, start, ...files] = args;
  write(start, [].concat(...files.map(f => JSON.parse(fs.readFileSync(f, 'utf8')))));
} else {
  const start = args[0] || '2025-01-01', end = args[1] || '2027-12-31';
  const t0 = Date.now();
  write(start, buildDays(start, end, (iso, sofar) => {
    if (sofar.length % 30 === 0) console.log(iso, ((Date.now() - t0) / 1000).toFixed(0) + 's');
  }));
}
