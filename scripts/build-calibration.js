#!/usr/bin/env node
// Builds www/data/calibration.js: six hard test puzzles graded A (gentlest) to F (toughest)
// by the difficulty meter, for tuning what "hard" should mean.
//   node scripts/build-calibration.js pool <file> <firstSeed> <count>   generate candidates
//   node scripts/build-calibration.js pick <file> [<file>...]           choose six and write the data file
const fs = require('fs');
const path = require('path');
const { encode } = require('./build-archive.js');
const { generateRated } = require('../www/js/rater.js');
const [mode, ...rest] = process.argv.slice(2);
if (mode === 'pool') {
  const [file, first, count] = rest;
  const pool = [];
  for (let i = +first; pool.length < +count; i++) {
    try {
      const p = generateRated('calibration:' + i, 'hard');
      pool.push({ puzzle: encode(p), rating: p.rating });
      fs.writeFileSync(file, JSON.stringify(pool));
    } catch (e) { /* this seed found nothing in its attempt budget; try the next */ }
  }
} else {
  const pool = [].concat(...rest.map(f => JSON.parse(fs.readFileSync(f, 'utf8'))));
  pool.sort((a, b) => a.rating.score - b.rating.score || a.rating.maxLinks - b.rating.maxLinks);
  const out = {};
  for (let k = 0; k < 6; k++) out['ABCDEF'[k]] = pool[Math.round(k * (pool.length - 1) / 5)];
  fs.writeFileSync(path.join(__dirname, '../www/data/calibration.js'),
    '/* Generated by scripts/build-calibration.js */\nself.SPOTLOCK_CALIB = ' + JSON.stringify(out) + ';\n');
  console.log('pool', pool.length, 'scores', pool.map(p => p.rating.score).join(','));
  console.log('picked', Object.entries(out).map(([l, p]) => l + ':' + JSON.stringify(p.rating)).join('\n'));
}
